/**
 * Каналы сборки.
 *
 * Один и тот же код собирается дважды:
 *
 *   • **stable** — то, что видят игроки (`https://telegup.mooo.com`);
 *   • **dev** — тот же проект, собранный с `VITE_CHANNEL=dev` и выложенный в
 *     подпапку `/dev/`. Туда попадают сборки, которые ещё не готовы к
 *     релизу: черновики, эксперименты, следующая версия.
 *
 * Пометка зашивается в саму сборку (а не читается из адреса), поэтому
 * «включить dev» на обычном сайте нельзя: печенька или `?dev=1` ничего не
 * меняют. Dev-сборка дополнительно закрыта владельцем — см. `ChannelGate`.
 */

export type Channel = "stable" | "dev";

/**
 * Значение подставляет `vite.config.ts` (`define`), потому что
 * `import.meta.env` в Vite видит только переменные из `.env*`, а канал
 * приходит переменной окружения сборки.
 */
export const CHANNEL: Channel = import.meta.env.VITE_CHANNEL === "dev" ? "dev" : "stable";

/** Идёт ли эта сборка по «раннему» каналу. */
export const IS_DEV_CHANNEL = CHANNEL === "dev";

/** Подпись для бейджа в интерфейсе. */
export const CHANNEL_LABEL = IS_DEV_CHANNEL ? "DEV" : "";